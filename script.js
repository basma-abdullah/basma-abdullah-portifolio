// --- Contact Form Handling (AJAX - JSON Fix) ---
// التأكد من أن الـ ID هنا يطابق الـ ID في الـ HTML
const contactForm = document.getElementById('contact-form-right');
const formStatus = document.getElementById('form-status');

if (contactForm) {
    contactForm.addEventListener('submit', async function(event) {
        event.preventDefault(); // منع تحديث الصفحة
        
        // 1. استخراج البيانات من الفورم
        const formData = new FormData(contactForm);
        
        // 2. تحويل البيانات إلى كائن JSON
        const data = Object.fromEntries(formData.entries());

        try {
            const response = await fetch(event.target.action, {
                method: 'POST', 
                body: JSON.stringify(data), // تحويل البيانات لنص JSON
                headers: {
                    'Content-Type': 'application/json',
                    'Accept': 'application/json'
                }
            });
            
            if (response.ok) {
                // نجاح الإرسال
                formStatus.innerHTML = "Thanks! Your message has been sent.";
                formStatus.style.color = "green";
                contactForm.reset(); // تفريغ الخانات
            } else {
                // فشل الإرسال
                const jsonData = await response.json();
                if (jsonData.errors) {
                    formStatus.innerHTML = jsonData.errors.map(error => error.message).join(", ");
                } else {
                    formStatus.innerHTML = "Oops! There was a problem submitting your form.";
                }
                formStatus.style.color = "red";
            }
        } catch (error) {
            // فشل الاتصال بالإنترنت
            formStatus.innerHTML = "Oops! There was a problem submitting your form.";
            formStatus.style.color = "red";
        }
    });
}