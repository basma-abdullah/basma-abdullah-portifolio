const langBtn = document.getElementById('lang-btn');
const htmlEl = document.documentElement;
let currentLang = 'en';

// دالة تحديث النصوص بناءً على اللغة الحالية
function updateContent() {
    htmlEl.setAttribute('lang', currentLang);
    htmlEl.setAttribute('dir', currentLang === 'ar' ? 'rtl' : 'ltr');
    langBtn.textContent = currentLang === 'en' ? 'عربي' : 'English';
    
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[currentLang][key]) {
            el.innerHTML = translations[currentLang][key];
        }
    });
}

// دالة التبديل عند الضغط
function toggleLang() {
    currentLang = currentLang === 'en' ? 'ar' : 'en';
    updateContent();
}

langBtn.addEventListener('click', toggleLang);

// --- هذا هو الجزء المهم (إصلاح المشكلة) ---
// تنفيذ التحديث فور تحميل الصفحة لضمان المقاسات الصحيحة
document.addEventListener('DOMContentLoaded', () => {
    updateContent(); 
});

// Scroll Logic
window.addEventListener('scroll', () => {
    const navbar = document.querySelector('.navbar');
    const heroSection = document.querySelector('.hero-section');
    if (window.scrollY > 50) {
        navbar.classList.add('scrolled');
        heroSection.classList.add('scrolled-hero');
    } else {
        navbar.classList.remove('scrolled');
        heroSection.classList.remove('scrolled-hero');
    }
});

